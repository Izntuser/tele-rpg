"""Declarative base, constraint naming convention, column helpers and model discovery."""

import importlib
import importlib.util
import pkgutil
import re
from datetime import datetime
from enum import StrEnum
from functools import cache
from typing import Any

from sqlalchemy import BigInteger, DateTime, Enum, Identity, MetaData, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    # Every timestamp is timestamptz (stored in UTC); every JSON document is jsonb.
    type_annotation_map = {
        datetime: DateTime(timezone=True),
        dict[str, Any]: JSONB,
    }


def pg_type_name(enum_cls: type[StrEnum]) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", enum_cls.__name__).lower()


@cache
def pg_enum(enum_cls: type[StrEnum]) -> Enum:
    """The single SQLAlchemy type for a shared enum; stores the enum *values* in Postgres."""
    return Enum(
        enum_cls,
        name=pg_type_name(enum_cls),
        values_callable=lambda cls: [member.value for member in cls],
        validate_strings=True,
    )


def id_pk() -> Mapped[int]:
    """``bigint GENERATED BY DEFAULT AS IDENTITY`` primary key."""
    return mapped_column(BigInteger, Identity(), primary_key=True)


def created_at() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)


def load_models() -> None:
    """Import every ``app.modules.<domain>.models`` so ``Base.metadata`` is complete."""
    import app.modules as modules_pkg

    for info in pkgutil.iter_modules(modules_pkg.__path__):
        if not info.ispkg:
            continue
        name = f"{modules_pkg.__name__}.{info.name}.models"
        if importlib.util.find_spec(name) is not None:
            importlib.import_module(name)
