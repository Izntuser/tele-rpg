"""Where uploaded bytes live (DECISIONS #8, ARCHITECTURE §2).

Routes and services only see ``StorageBackend``; ``LocalStorage`` (a directory, a Railway volume
in prod) is the one implementation, and an S3 backend can replace it without route changes.
Keys are generated by the server (``new_key``), never taken from a client; every backend must
still reject a key that does not match ``KEY_PATTERN``.
"""

import re
import secrets
from abc import ABC, abstractmethod
from collections.abc import AsyncIterator
from functools import lru_cache

from app.core.config import get_settings
from app.modules.common.enums import FileKind

#: ``<kind>/<32 hex>.<ext>``: no dots, slashes or other path syntax a caller could abuse.
KEY_PATTERN = re.compile(r"^(avatar|quest_photo|reward_image)/[0-9a-f]{32}\.(jpg|webp)$")
CHUNK_SIZE = 64 * 1024


class InvalidKeyError(ValueError):
    """The storage key is not one ``new_key`` could have produced."""


class StoredFileNotFoundError(LookupError):
    """No bytes are stored under the key."""


def new_key(kind: FileKind, extension: str) -> str:
    """A fresh, unguessable key (128 random bits) for a file of ``kind``."""
    key = f"{kind.value}/{secrets.token_hex(16)}.{extension}"
    return validate_key(key)


def validate_key(key: str) -> str:
    if not KEY_PATTERN.fullmatch(key):
        raise InvalidKeyError(key)
    return key


class StorageBackend(ABC):
    @abstractmethod
    async def put(self, key: str, data: bytes) -> None:
        """Store ``data`` under ``key`` (atomically: readers never see a partial file)."""

    @abstractmethod
    def open(self, key: str) -> AsyncIterator[bytes]:
        """The stored bytes in chunks; raises ``StoredFileNotFoundError`` before the first
        chunk when nothing is stored under ``key``."""

    @abstractmethod
    async def delete(self, key: str) -> None:
        """Remove the bytes; a missing key is not an error."""

    @abstractmethod
    async def exists(self, key: str) -> bool: ...


@lru_cache
def _default_storage() -> StorageBackend:
    from app.storage.local import LocalStorage

    return LocalStorage(get_settings().storage_dir)


def get_storage() -> StorageBackend:
    """FastAPI dependency (tests override it with a ``LocalStorage`` on a tmp dir)."""
    return _default_storage()
